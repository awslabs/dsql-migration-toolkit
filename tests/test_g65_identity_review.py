def test_full_load_binds_a_whole_decimal_key_as_an_integer() -> None:
    """A numeric(12,0) serial key made a bigint identity comes off psycopg as a Decimal:
    bound as numeric, the SELECT-filter's `"id" IN (...)` could not use the key."""
    from dsql_migrator.core.batched_import import _key_parameter

    assert _key_parameter(Decimal("42")) == 42 and isinstance(_key_parameter(Decimal("42")), int)
    assert _key_parameter(Decimal("42.000")) == 42
    assert _key_parameter(Decimal("1.5")) == Decimal("1.5")
    assert _key_parameter(Decimal("NaN")).is_nan()
    assert _key_parameter("abc") == "abc" and _key_parameter(7) == 7


def _pg_key(type_: str) -> TableDef:
    return TableDef(
        name="app.orders",
        columns=[ColumnDef(name="id", mysql_type=type_, nullable=False,
                           default="nextval('app.orders_id_seq'::regclass)")],
        primary_key=["id"],
        auto_increment_column="id",
    )


def test_a_numeric_key_made_an_identity_gets_no_numeric_advice() -> None:
    """A bare numeric serial key became BIGINT ... AS IDENTITY, yet both steps said it is
    stored at numeric(18,6) and to give it an explicit numeric(p,s) -- which would remove
    the identity."""
    table = _pg_key("numeric")
    (converted,) = SchemaConverter(source_type=SourceType.POSTGRES).convert(
        SourceInventory(tables=[table])
    ).tables
    assert "GENERATED BY DEFAULT AS IDENTITY" in converted.target_ddl
    messages = [w.message for w in converted.warnings]
    assert not any("numeric(18,6)" in m for m in messages)
    narrowing = [m for m in messages if "was narrowed from" in m]
    assert narrowing and "fractional part" in narrowing[0] and "2^63-1" in narrowing[0]
    (item,) = CompatibilityAssessor(source_type=SourceType.POSTGRES).assess(
        SourceInventory(tables=[table])
    ).items
    assert "PG_UNCONSTRAINED_NUMERIC" not in {c.rule_id for c in item.concerns}


def test_a_numeric_key_bigint_holds_whole_is_not_called_narrowed() -> None:
    for type_, says in (
        ("numeric(12,0)", None),
        ("numeric(20,0)", "2^63-1"),
        ("numeric(10,2)", "fractional part"),
    ):
        (converted,) = SchemaConverter(source_type=SourceType.POSTGRES).convert(
            SourceInventory(tables=[_pg_key(type_)])
        ).tables
        narrowing = [w.message for w in converted.warnings if "was narrowed from" in w.message]
        if says is None:
            assert narrowing == [], type_
        else:
            assert narrowing and says in narrowing[0], type_


def test_the_picker_choice_brings_its_own_notes() -> None:
    """After a per-table pick the screen still showed the DEFAULT strategy's notes: an
    identity DDL captioned 'kept as a plain integer', and Keep source PK beside a note
    saying the key keeps generating."""
    from dsql_migrator.ui.schema_conversion import (
        TABLE_PREFIX,
        generate_previews,
        render_target_ddl,
    )
    from dsql_migrator.ui.schema_conversion_apply import (
        build_identity_conversion,
        build_keep_conversion,
    )

    unsigned = TableDef(
        name="shop.orders",
        columns=[ColumnDef(name="id", mysql_type="bigint unsigned", nullable=False)],
        primary_key=["id"],
        auto_increment_column="id",
    )
    signed = unsigned.model_copy(update={
        "name": "shop.users",
        "columns": [ColumnDef(name="id", mysql_type="int", nullable=False)],
    })
    inventory = SourceInventory(tables=[unsigned, signed])
    converter = SchemaConverter()
    result = converter.convert(inventory)
    stored = {
        "shop.orders": render_target_ddl(build_identity_conversion(converter, unsigned)),
        "shop.users": render_target_ddl(build_keep_conversion(converter, signed)),
    }
    previews = {
        p.object_name: p
        for p in generate_previews(
            [TABLE_PREFIX + "shop.orders", TABLE_PREFIX + "shop.users"],
            inventory, result, stored_ddl_of=stored.get,
        )
    }
    orders = " ".join(w.message for w in previews["shop.orders"].warnings)
    assert "KEEPS its value generation" in orders and "was narrowed from" in orders
    assert "kept as a plain integer" not in orders
    users = " ".join(w.message for w in previews["shop.users"].warnings)
    assert "kept as a plain integer" in users and "KEEPS its value generation" not in users
    # Nothing stored: the default conversion's notes, as before.
    (plain,) = generate_previews([TABLE_PREFIX + "shop.users"], inventory, result)
    assert "KEEPS its value generation" in " ".join(w.message for w in plain.warnings)


def test_a_column_cdc_drops_is_worded_by_its_target_default() -> None:
    """'refuses EVERY insert and update' ignored a target DEFAULT (rows land with it), and
    'NULL on every row' an update (the upsert never names the column: it stays as it was);
    a NOT NULL bit(n)[] stops the PostgreSQL source connector instead."""
    from dsql_migrator.core.prerequisites_postgres import (
        UNCARRYABLE_COLUMN_ARRIVES_NULL,
        UncarryableCdcColumn,
        target_defaulted_columns,
        uncarryable_column_texts,
    )

    def col(name: str, type_: str, nullable: bool) -> UncarryableCdcColumn:
        return UncarryableCdcColumn(
            column=name, declared_type=type_, reason=UNCARRYABLE_COLUMN_ARRIVES_NULL,
            nullable=nullable,
        )

    table = TableDef(
        name="app.t",
        columns=[
            ColumnDef(name="id", mysql_type="bigint", nullable=False),
            ColumnDef(name="spans", mysql_type="interval[]", type_kind="array", nullable=False,
                      default="'{}'::interval[]"),
        ],
        primary_key=["id"],
    )
    assert target_defaulted_columns(table) == {"spans"}
    what, _todo = uncarryable_column_texts(
        [col("spans", "interval[]", False)], defaulted=target_defaulted_columns(table)
    )
    assert "refuses" not in what
    assert "a row CDC inserts gets the column's DEFAULT and an update leaves it as before" in what
    what, todo = uncarryable_column_texts([col("flags", "bit(8)[]", False)])
    assert "STOPS the PostgreSQL source connector" in what and "refuses" not in what
    assert "drop the NOT NULL" not in todo  # the source schema is what makes it required
    what, _todo = uncarryable_column_texts([col("flags", "bit(8)[]", True)])
    assert "NULL on every row CDC delivers" in what


def _fk_tables() -> "tuple[TableDef, TableDef]":
    from dsql_migrator.core.models import ForeignKeyDef

    customers = TableDef(
        name="shop.customers",
        columns=[ColumnDef(name="id", mysql_type="int", nullable=False)],
        primary_key=["id"],
    )
    orders = TableDef(
        name="shop.orders",
        columns=[
            ColumnDef(name="id", mysql_type="int", nullable=False),
            ColumnDef(name="customer_id", mysql_type="int"),
            ColumnDef(name="created", mysql_type="datetime"),
        ],
        primary_key=["id"],
        auto_increment_column="id",
        foreign_keys=[ForeignKeyDef(
            name="fk_orders_customer", columns=["customer_id"],
            referenced_table="shop.customers", referenced_columns=["id"],
        )],
    )
    return customers, orders


def test_a_pick_swaps_only_the_strategy_notes() -> None:
    """G75: the swap replaced the whole note list with a per-table conversion's: with
    'preserve foreign keys' off the table said its FKs were preserved (losing the 'removed
    at your request' LOSS), and an index rename's note vanished."""
    from dsql_migrator.core.converter import SchemaConvertOptions
    from dsql_migrator.ui.schema_conversion import (
        TABLE_PREFIX,
        generate_previews,
        render_target_ddl,
    )
    from dsql_migrator.ui.schema_conversion_apply import build_keep_conversion

    customers, orders = _fk_tables()
    inventory = SourceInventory(tables=[customers, orders])
    converter = SchemaConverter()
    result = converter.convert(inventory, SchemaConvertOptions(preserve_foreign_keys=False))
    stored = {"shop.orders": render_target_ddl(build_keep_conversion(converter, orders))}
    (preview,) = generate_previews(
        [TABLE_PREFIX + "shop.orders"], inventory, result, stored_ddl_of=stored.get
    )
    notes = " ".join(w.message for w in preview.warnings)
    assert "kept as a plain integer" in notes
    assert "KEEPS its value generation" not in notes
    assert "removed at your request" in notes
    assert "are preserved and re-created" not in notes


