"""G63: the review of G44-G55 -- serial DEFAULT spellings, sequence-formatting DEFAULTs,
functions a DEFAULT calls from the search path, and the cost of resolving defaults."""

from __future__ import annotations

import pytest

from dsql_migrator.core.assessor import CompatibilityAssessor
from dsql_migrator.core.converter import SchemaConverter
from dsql_migrator.core.converter_postgres import (
    pg_column_default_sql,
    pg_is_bare_nextval,
    pg_nextval_sequence,
)
from dsql_migrator.core.models import ColumnDef, SourceInventory, SourceType, TableDef
from tests.test_source_dialect import _DispatchPgConnection

_PG = SourceType.POSTGRES


@pytest.mark.parametrize(
    "default",
    [
        "nextval('orders_id_seq'::regclass)",
        "(nextval('orders_id_seq'::regclass))::integer",
        "(nextval('\"app\".orders_id_seq'::regclass))::integer",
        "nextval(('app.orders_id_seq'::text)::regclass)",
        "(nextval(('app.orders_id_seq'::text)::regclass))::integer",
        "nextval('s'::regclass)::numeric(12,0)",
    ],
)
def test_every_serial_spelling_is_the_generated_key(default: str) -> None:
    assert pg_is_bare_nextval(default)
    assert pg_nextval_sequence(default) is not None


@pytest.mark.parametrize(
    "default",
    [
        "('ORD-'::text || lpad((nextval('s'::regclass))::text, 8, '0'::text))",
        "(nextval('s'::regclass) * 10)",
        "nextval('s'::regclass) + 1",
        "(nextval('a'::regclass)) + (nextval('b'::regclass))",
    ],
)
def test_an_expression_over_a_sequence_value_is_not(default: str) -> None:
    assert not pg_is_bare_nextval(default)


def _enriched(columns: "list[dict]", table: TableDef) -> TableDef:
    from dsql_migrator.core.source_dialect.postgres import _pg_enrich_columns

    _pg_enrich_columns(_DispatchPgConnection({"pg_attribute": lambda _p: columns}), "app", [table])
    return table


def test_a_cast_wrapped_or_late_binding_serial_key_keeps_its_identity() -> None:
    """G51 anchored the serial test on ^nextval(: an int key with the cast pg_get_expr
    prints lost its identity, read 100 'Ready', and rejected every INSERT omitting it."""
    for default in (
        "(nextval('app.orders_id_seq'::regclass))::integer",
        "nextval(('app.orders_id_seq'::text)::regclass)",
    ):
        table = _enriched(
            [{"col": "id", "typ": "integer", "gen": "", "ident": ""}],
            TableDef(
                name="orders",
                columns=[ColumnDef(name="id", mysql_type="integer", nullable=False, default=default)],
                primary_key=["id"],
            ),
        )
        assert table.auto_increment_column == "id"
        table = table.model_copy(update={"name": "app.orders"})
        (converted,) = SchemaConverter(source_type=_PG).convert(SourceInventory(tables=[table])).tables
        assert "GENERATED BY DEFAULT AS IDENTITY" in converted.target_ddl


def test_a_non_integer_key_fed_by_a_sequence_is_said_not_silent() -> None:
    """G51's type gate left a double precision / varchar serial key unflagged: its DEFAULT
    was dropped with no note at either step, and every INSERT omitting it was rejected."""
    table = _enriched(
        [{"col": "id", "typ": "double precision", "gen": "", "ident": ""}],
        TableDef(
            name="dbl_key",
            columns=[ColumnDef(name="id", mysql_type="double precision", nullable=False,
                               default="nextval('app.s'::regclass)")],
            primary_key=["id"],
        ),
    )
    assert table.auto_increment_column == "id"
    table = table.model_copy(update={"name": "app.dbl_key"})
    inventory = SourceInventory(tables=[table])
    (converted,) = SchemaConverter(source_type=_PG).convert(inventory).tables
    assert "IDENTITY" not in converted.target_ddl
    assert any("not an integer" in w.message for w in converted.warnings)
    (item,) = CompatibilityAssessor(source_type=_PG).assess(inventory).items
    assert item.classification.value == "MANUAL"


def test_a_formatted_sequence_default_is_a_drop_note_not_identity_advice() -> None:
    formatted = "('INV-'::text || lpad((nextval('app.inv_seq'::regclass))::text, 8, '0'::text))"
    column = ColumnDef(name="invoice_no", mysql_type="text", nullable=False, default=formatted)
    _emitted, reason = pg_column_default_sql(column)
    assert 'CREATE SEQUENCE "app"."inv_seq" CACHE 1 START WITH <its next value>' in reason
    assert "Step 1 item" not in reason  # an OWNED BY sequence has none
    inventory = SourceInventory(tables=[TableDef(
        name="app.invoices",
        columns=[ColumnDef(name="id", mysql_type="bigint", nullable=False), column],
        primary_key=["id"],
    )])
    (item,) = CompatibilityAssessor(source_type=_PG).assess(inventory).items
    rules = {c.rule_id for c in item.concerns}
    assert "DEFAULT_DROPPED" in rules and "NON_KEY_SEQUENCE" not in rules


def test_a_default_calling_a_search_path_function_is_dropped_not_carried() -> None:
    """pg_get_expr prints a public function bare, so next_token() was carried verbatim and
    the CREATE TABLE failed on Aurora DSQL while Evaluation read AUTO."""
    table = _enriched(
        [
            {"col": "id", "typ": "bigint", "gen": "", "ident": "d"},
            {"col": "token", "typ": "character varying(64)", "gen": "", "ident": "",
             "default_functions": ["public.next_token"], "default_function_names": ["next_token"]},
            {"col": "u", "typ": "uuid", "gen": "", "ident": "",
             "default_functions": ["public.gen_random_uuid"],
             "default_function_names": ["gen_random_uuid"]},
            {"col": "label", "typ": "text", "gen": "", "ident": "",
             "default_functions": ["public.next_token"], "default_function_names": ["next_token"]},
        ],
        TableDef(
            name="tokens",
            columns=[
                ColumnDef(name="id", mysql_type="bigint", nullable=False),
                ColumnDef(name="token", mysql_type="varchar(64)", nullable=False,
                          default="next_token()"),
                ColumnDef(name="u", mysql_type="uuid", default="gen_random_uuid()"),
                ColumnDef(name="label", mysql_type="text",
                          default="('next_token()'::text || next_token())"),
            ],
            primary_key=["id"],
        ),
    )
    by_name = {c.name: c for c in table.columns}
    assert by_name["token"].default == "public.next_token()"
    # pgcrypto's copy (an upgraded database) is the built-in on Aurora DSQL.
    assert pg_column_default_sql(by_name["u"]) == ("gen_random_uuid()", None)
    assert by_name["label"].default == "('next_token()'::text || public.next_token())"
    emitted, reason = pg_column_default_sql(by_name["token"])
    assert emitted is None and "public.next_token()" in reason
    table = table.model_copy(update={"name": "app.tokens"})
    (item,) = CompatibilityAssessor(source_type=_PG).assess(SourceInventory(tables=[table])).items
    assert "DEFAULT_DROPPED" in {c.rule_id for c in item.concerns}


def test_resolving_the_same_default_twice_parses_once() -> None:
    """DEFAULT_DROPPED re-resolved every default with an uncached sqlglot parse: 3,000
    tables took 4.6 s per assess instead of 0.4 s."""
    from dsql_migrator.core.converter import _resolved_mysql_default
    from dsql_migrator.core.converter_postgres import _pg_default_parses

    _resolved_mysql_default.cache_clear()
    _pg_default_parses.cache_clear()
    tables = [
        TableDef(
            name=f"app.t{i}",
            columns=[ColumnDef(name="id", mysql_type="int", nullable=False)]
            + [ColumnDef(name=f"c{j}", mysql_type="varchar(20)", default="'x'") for j in range(5)],
            primary_key=["id"],
        )
        for i in range(50)
    ]
    CompatibilityAssessor(source_type=SourceType.MYSQL).assess(SourceInventory(tables=tables))
    assert _resolved_mysql_default.cache_info().misses == 1
    pg_tables = [
        t.model_copy(update={"columns": [
            c.model_copy(update={"mysql_type": "text", "default": "'x'::text"}) for c in t.columns
        ]})
        for t in tables
    ]
    CompatibilityAssessor(source_type=_PG).assess(SourceInventory(tables=pg_tables))
    assert _pg_default_parses.cache_info().misses == 1
