"""The AI DBA's system prompts: each chat scope's grounding, as text.

Split out of :mod:`dsql_migrator.core.assessment_strategist` (A11), which sends the
chats to Amazon Bedrock: this module only WRITES the grounding a chat is sent with --
the known Aurora DSQL constraints (:data:`DSQL_CONSTRAINTS`), the query-efficiency
rubric, the Full Load / CDC / Validation recovery contexts and one ``build_*_system``
function per scope (an object, the general panel, a conversion, a reimplementation, a
query and its tuning, a validation mismatch, a failed Full Load table, a CDC problem, a
connection error). Pure: no Bedrock client, no session, no connection. The response-style
directive, the answer tool and the token budgets are the call's, and stay with the
strategist. :mod:`~dsql_migrator.core.assessment_strategist` re-exports every name below,
so ``from dsql_migrator.core.assessment_strategist import ...`` keeps working; this module
imports nothing of it, so either can be imported first.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Optional

from dsql_migrator.core.models import AssessmentItem


# Cap on each piece of grounding text a prompt embeds (a DDL, a query, a plan, the
# facts), so a prompt stays bounded however large its inputs are.
_MAX_TEXT_CHARS = 4000

# Aurora DSQL constraints the AI DBA's chats are grounded on. Mirrors the
# constraints the deterministic assessor/converter apply so the AI analysis
# stays consistent with the factual backbone.
DSQL_CONSTRAINTS = (
    "Aurora DSQL constraints: foreign keys ARE supported and enforced (preserved "
    "and re-created after the data load, with extra-read cost and a 3000-row limit "
    "on CASCADE actions); Aurora DSQL can create a table without a primary key, but this "
    "migration tool needs one (Full Load reads by primary-key keyset, CDC applies changes "
    "by key); secondary indexes are created asynchronously (CREATE INDEX ASYNC), partial "
    "and expression indexes are supported, and json/jsonb/interval/timetz/bytea columns "
    "cannot be indexed; the 'C' collation is used; triggers and stored procedures are "
    "unsupported; a single-column integer generated key (auto-increment, serial or "
    "identity) that bigint can hold becomes a cached identity by default (bigint "
    "GENERATED BY DEFAULT AS IDENTITY, CACHE 65536), which keeps generating values and "
    "spreads inserts; a numeric key fed by a sequence becomes one too, narrowed to "
    "bigint (a value bigint cannot hold would not load); an unsigned 64-bit key (kept "
    "numeric(20,0) for its range) or a composite one is kept WITHOUT generation (the "
    "application must supply it), and a key "
    "the application supplies in increasing order concentrates writes on one partition; "
    "source-side "
    "native/declarative partitioning is not used (DSQL distributes data automatically); "
    "spatial/geometry types have no lossless mapping; numeric precision goes up to 1000; "
    "STORED generated columns ARE supported (GENERATED ALWAYS AS (expr) STORED) and Aurora "
    "DSQL maintains them -- an INSERT/UPDATE must NOT supply a value for such a column; "
    "VIRTUAL generated columns are not supported; an expression can be DROPPED from a "
    "column but never ADDED to an existing one; there are transaction limits (a single "
    "DDL statement per transaction, at most 3000 rows per transaction)."
)


def build_object_chat_system(item: AssessmentItem, *, source_engine: str = "MySQL") -> str:
    """Build the system grounding for a multi-turn chat about ONE object.

    This is the persistent system context for a back-and-forth conversation: it
    pins the model to ONE deterministic :class:`AssessmentItem` and the DSQL
    constraints, sets a natural, conversational tone, and tells it the
    deterministic facts are authoritative. The turns themselves (the initial
    question and any follow-ups) are supplied as the chat ``messages``.
    """
    effort = item.effort.value if item.effort is not None else "NONE"
    return (
        "You are a senior AWS database migration engineer chatting with a "
        f"teammate who is migrating a {source_engine} database to Amazon Aurora DSQL "
        "(PostgreSQL-16 wire-compatible). The SOURCE engine is "
        f"{source_engine}; the TARGET is Aurora DSQL, so any reimplemented / converted "
        "SQL must be written in DSQL's PostgreSQL dialect (not the source dialect). "
        "Answer naturally and conversationally, the way "
        "you would in a chat — explain things in your own words, in a friendly, "
        "helpful tone, and answer follow-up questions in context. Do NOT use a "
        "rigid template or fixed section headings. Light GitHub-flavored Markdown "
        "is fine (a little emphasis, an occasional short list or fenced code "
        "block) but keep it reading like a natural reply, not a form. Be specific "
        "and reasonably concise.\n\n"
        "Your focus is migrating THIS object to Aurora DSQL, but you are also this "
        "migration's assistant. If the user asks about the WIDER migration -- other "
        "objects, the assessment as a whole, converted DDL, validation results, load "
        "status -- help them: USE ANY TOOLS you have to look up the real data and "
        "answer, rather than refusing just because it is not this object. Only decline "
        f"questions that are genuinely off-topic for a {source_engine} -> Aurora DSQL "
        "migration (unrelated technologies, general chit-chat), politely, in one "
        "sentence.\n\n"
        "The conversation is about this single object, which a deterministic, "
        "rule-based assessment flagged. These facts are authoritative — build on "
        "them and never contradict them:\n"
        f"- Object: {item.object_name}\n"
        f"- Kind: {item.kind}\n"
        f"- Classification: {item.classification.value}\n"
        f"- Estimated manual effort: {effort}\n"
        f"- Rule: {item.rule_id}\n"
        f"- Risk: {item.risk or '(none recorded)'}\n"
        f"- Recommendation: {item.recommendation or '(none)'}\n\n"
        f"Aurora DSQL constraints:\n{DSQL_CONSTRAINTS}"
    )


def build_general_chat_system(
    *, current_step: str = "", migration_type: str = "", summary: str = "",
    source_engine: str = "MySQL",
) -> str:
    """System grounding for the GENERAL (no specific object) assistant panel.

    Opened from the header, the persistent panel lets the user ask about the
    migration as a whole. This pins it to a MySQL -> Amazon Aurora DSQL migration
    assistant: it answers questions about THIS migration (schema conversion, data
    migration / CDC, validation, cut over, DSQL behavior and constraints) and the
    current progress -- grounded on the credential-free
    :class:`~dsql_migrator.core.models.MigrationContext` -- and DECLINES anything
    off-topic, using the SAME guardrail wording as the per-object chats. No
    credentials or row data ever enter the prompt (Property 7).
    """
    where = []
    if current_step:
        where.append(f"- Current step: {current_step}")
    if migration_type:
        where.append(f"- Migration type: {migration_type}")
    if summary:
        where.append(f"- Notes: {summary}")
    context_block = "\n".join(where) or "- (no step context captured yet)"
    return (
        "You are a senior AWS database migration engineer chatting with a teammate "
        f"who is migrating a {source_engine} database to Amazon Aurora DSQL "
        "(PostgreSQL-16 wire-compatible) using this tool. The SOURCE engine is "
        f"{source_engine}; the TARGET is Aurora DSQL, so converted/reimplemented SQL "
        "is written in DSQL's PostgreSQL dialect (not the source dialect). Answer "
        "naturally and conversationally; light GitHub-flavored Markdown is fine, but "
        "keep it reading like a natural reply, not a form. Be specific and reasonably "
        "concise.\n\n"
        f"Stay strictly on the topic of THIS {source_engine} -> Aurora DSQL migration: "
        "schema "
        "conversion, data migration (Full Load / CDC), validation, cut over, and "
        "Aurora DSQL behavior/constraints, plus the current progress. If the user "
        "asks about anything off-topic — unrelated technologies, other systems, "
        "general chit-chat, or non-migration questions — politely decline in one "
        "sentence and steer back to the migration.\n\n"
        "Where the user is in the tool (deterministic, authoritative — never "
        "contradict it):\n"
        f"{context_block}\n\n"
        f"Aurora DSQL constraints:\n{DSQL_CONSTRAINTS}"
    )


